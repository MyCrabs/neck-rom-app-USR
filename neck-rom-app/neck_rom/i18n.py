class T:
    def __init__(self, lang: str = "zh"):
        self.lang = lang

    def toggle(self):
        self.lang = "en" if self.lang == "zh" else "zh"

    def __call__(self, key: str, **kw) -> str:
        s = STRINGS[self.lang].get(key) or STRINGS["en"].get(key, key)
        return s.format(**kw) if kw else s
